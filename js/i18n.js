/* ── Engine ── */
let currentLang = localStorage.getItem('ts_lang') || 'en';

function t(key) {
  return (T[currentLang] && T[currentLang][key]) || (T.en && T.en[key]) || key;
}

function applyLang(lang) {
  currentLang = lang;
  localStorage.setItem('ts_lang', lang);
  const info = LANGUAGES.find(l => l.code === lang) || LANGUAGES[0];
  document.documentElement.lang = lang;
  document.documentElement.dir = info.dir;
  // Text content elements
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    const val = t(key);
    if (el.dataset.i18nHtml !== undefined || key === 'hero.title') {
      el.innerHTML = val;
    } else {
      el.textContent = val;
    }
  });
  // HTML content elements
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    el.innerHTML = t(el.dataset.i18nHtml);
  });
  // Update switcher labels
  const label = document.getElementById('langLabel');
  const footerLabel = document.getElementById('footerLangLabel');
  if (label) label.textContent = info.name;
  if (footerLabel) footerLabel.textContent = info.name;
  // Update active states
  document.querySelectorAll('.lang-option').forEach(opt => {
    opt.classList.toggle('active', opt.dataset.lang === lang);
    opt.innerHTML = opt.dataset.lang === lang
      ? `${LANGUAGES.find(l=>l.code===opt.dataset.lang)?.name || opt.dataset.lang} <i class="ph ph-check"></i>`
      : (LANGUAGES.find(l=>l.code===opt.dataset.lang)?.name || opt.dataset.lang);
  });
  // RTL adjustments
  if (info.dir === 'rtl') {
    document.body.style.setProperty('--text-align-start','right');
  } else {
    document.body.style.setProperty('--text-align-start','left');
  }
}

function initLangSwitcher() {
  const btn = document.getElementById('langBtn');
  const dropdown = document.getElementById('langDropdown');
  const footerBtn = document.getElementById('footerLangBtn');
  const footerDropdown = document.getElementById('footerLangDropdown');
  if (!btn || !dropdown) return;

  const buildDropdown = (dd) => {
    if (!dd) return;
    dd.innerHTML = LANGUAGES.map(l => `
      <button class="lang-option${l.code === currentLang ? ' active' : ''}" data-lang="${l.code}">
        ${l.name}${l.code === currentLang ? ' <i class="ph ph-check"></i>' : ''}
      </button>
    `).join('');
    dd.querySelectorAll('.lang-option').forEach(opt => {
      opt.addEventListener('click', () => {
        applyLang(opt.dataset.lang);
        dropdown.classList.remove('open');
        if (footerDropdown) footerDropdown.classList.remove('open');
      });
    });
  };

  buildDropdown(dropdown);
  buildDropdown(footerDropdown);

  btn.addEventListener('click', e => { e.stopPropagation(); dropdown.classList.toggle('open'); });
  if (footerBtn) {
    footerBtn.addEventListener('click', e => { e.stopPropagation(); if(footerDropdown) footerDropdown.classList.toggle('open'); });
  }
  document.addEventListener('click', () => {
    dropdown.classList.remove('open');
    if (footerDropdown) footerDropdown.classList.remove('open');
  });
}

document.addEventListener('DOMContentLoaded', () => {
  applyLang(currentLang);
  initLangSwitcher();
});

